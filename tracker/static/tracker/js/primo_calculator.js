/**
 * Rota a la izquierda un array de bytes.
 */
function rotateBytesLeft(bytes, numBytes, amt) {
    amt %= (numBytes * 8);
    const last = numBytes - 1;
    let byteRotate = Math.floor(amt / 8);
    const bitRotate = amt % 8;

    while (byteRotate--) {
        const tmp = bytes[0];
        for (let i = 0; i < last; i++) {
            bytes[i] = bytes[i + 1];
        }
        bytes[last] = tmp;
    }

    if (bitRotate !== 0) {
        const tmp = bytes[0];
        for (let i = 0; i < last; i++) {
            bytes[i] = ((bytes[i] << bitRotate) | (bytes[i + 1] >> (8 - bitRotate))) & 0xFF;
        }
        bytes[last] = ((bytes[last] << bitRotate) | (tmp >> (8 - bitRotate))) & 0xFF;
    }
}

/**
 * Calcula los 4 índices de palabras para una recompensa según el Trainer ID.
 * @param {number} trainerId - ID de Entrenador (0 - 65535)
 * @param {number} rewardId - ID de la recompensa (0 - 10)
 * @returns {Array<number>} 4 índices enteros.
 */
export function getPrimoIndices(trainerId, rewardId) {
    const magicNumber = 6;
    const bytes = new Array(4);
    bytes[0] = (magicNumber << 4) | (rewardId & 0x0F);
    bytes[1] = (trainerId >> 8) & 0xFF;
    bytes[2] = trainerId & 0xFF;
    bytes[3] = ((bytes[0] + bytes[1]) * bytes[2]) % 256;

    bytes[1] ^= bytes[0];
    bytes[2] ^= bytes[0];

    rotateBytesLeft(bytes, 3, bytes[3] % 16);

    const xorVal = (bytes[3] >> 4) | (bytes[3] & 0xF0);
    bytes[0] ^= xorVal;
    bytes[1] ^= xorVal;
    bytes[2] ^= xorVal;

    rotateBytesLeft(bytes, 4, 5);

    const idx = new Array(4);
    idx[0] = bytes[0];
    for (let i = 1; i < 4; i++) {
        idx[i] = idx[i - 1] + bytes[i];
    }

    return idx;
}

/**
 * Calcula la frase de 4 palabras para una recompensa específica.
 * @param {number} trainerId - ID de Entrenador (0 - 65535)
 * @param {number} rewardId - ID de recompensa (0 a 10)
 * @param {string} lang - Idioma ('es' o 'en')
 * @returns {Object|null} { words: [w0, w1, w2, w3], line1: [w0, w1], line2: [w2, w3] }
 */
export function calculatePrimoWords(trainerId, rewardId, lang = 'es') {
    const tid = parseInt(trainerId, 10);
    if (isNaN(tid) || tid < 0 || tid > 65535) return null;
    if (typeof rewardId !== 'number' || rewardId < 0 || rewardId > 10) return null;

    const wordsTable = (lang === 'en') ? PRIMO_WORDS_EN : PRIMO_WORDS_ES;
    const tableLength = wordsTable.length;
    const indices = getPrimoIndices(tid, rewardId);

    const words = indices.map(idx => wordsTable[idx % tableLength]);

    return {
        words,
        line1: [words[0], words[1]],
        line2: [words[2], words[3]]
    };
}

/**
 * Obtiene todas las recompensas calculadas (3 huevos y 8 fondos de PC).
 * @param {number} trainerId - ID de Entrenador (0 - 65535)
 * @param {string} lang - Idioma ('es' o 'en')
 * @returns {Object|null} { eggs: Array, wallpapers: Array }
 */
export function getAllPrimoRewards(trainerId, lang = 'es') {
    const tid = parseInt(trainerId, 10);
    if (isNaN(tid) || tid < 0 || tid > 65535) return null;

    const eggs = PRIMO_EGGS.map(egg => ({
        ...egg,
        calc: calculatePrimoWords(tid, egg.id, lang)
    }));

    const wallpapers = PRIMO_WALLPAPERS.map(wp => ({
        ...wp,
        calc: calculatePrimoWords(tid, wp.id, lang)
    }));

    return { eggs, wallpapers };
}
